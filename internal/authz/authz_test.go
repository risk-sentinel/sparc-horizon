const (
	oscalDir   = "../../fixtures/oscal"
	oscalGlob  = "ssp-*.json"
	apiDir     = "../../fixtures/api"
	personaFil = "personas.json"
)

// persona is the caller description frozen into the fixtures in #61.
type persona struct {
	ID        string `json:"id"`
	Role      string `json:"role"`
	PartyUUID string `json:"party-uuid"`
	NodeUUID  string `json:"node-uuid"`
	NodeType  string `json:"node-type"`
	Name      string `json:"name"`
}

// treeResult builds the tree from the committed OSCAL fixtures. Read through an
// fs.FS rooted at the fixture directory so nothing outside it is reachable.
func treeResult(t *testing.T) tree.Result {
	t.Helper()

	fsys := os.DirFS(oscalDir)
	names, err := fs.Glob(fsys, oscalGlob)
	if err != nil || len(names) == 0 {
		t.Fatalf("no SSP fixtures: %v", err)
	}
	sort.Strings(names)

	var ssps []*oscal.SystemSecurityPlan
	for _, n := range names {
		b, err := fs.ReadFile(fsys, n)
		if err != nil {
			t.Fatalf("%s: %v", n, err)
		}
		var doc oscal.OscalCompleteSchema
		if err := json.Unmarshal(b, &doc); err != nil {
			t.Fatalf("%s: %v", n, err)
		}
		ssps = append(ssps, doc.SystemSecurityPlan)
	}

	res, err := tree.Build(ssps)
	if err != nil {
		t.Fatalf("tree.Build: %v", err)
	}
	return res
}

func authorizer(t *testing.T) *Authorizer {
	t.Helper()
	a, err := New(treeResult(t))
	if err != nil {
		t.Fatalf("authz.New: %v", err)
	}
	return a
}

func personas(t *testing.T) []persona {
	t.Helper()
	b, err := fs.ReadFile(os.DirFS(apiDir), personaFil)
	if err != nil {
		t.Fatalf("personas: %v", err)
	}
	var out []persona
	if err := json.Unmarshal(b, &out); err != nil {
		t.Fatalf("personas: %v", err)
	}
	if len(out) == 0 {
		t.Fatal("no personas; there is nothing to check against")
	}
	return out
}

// The exit criterion on #76, and the strongest evidence available here: the
// computed subtree must equal the golden frozen in #61 — written before this
// package existed, and served by cmd/mockserver as the contract's answer.
//
// Stated plainly: those goldens are generated by internal/fixtures, so
// agreement proves the two implementations agree, not that either is
// independently right. It is still the constraint worth having, because the
// goldens are what the API promises and they are schema-validated in CI.
func TestSubtreeMatchesTheFrozenPersonaGoldens(t *testing.T) {
	a := authorizer(t)
	fsys := os.DirFS(apiDir)

	for _, p := range personas(t) {
		t.Run(p.ID, func(t *testing.T) {
			raw, err := fs.ReadFile(fsys, p.ID+"/tree.json")
			if err != nil {
				t.Fatalf("golden: %v", err)
			}

			got := a.Subtree(p.PartyUUID)
			if got == nil {
				t.Fatalf("%s holds nothing; the golden says it roots at %s %s", p.ID, p.NodeType, p.NodeUUID)
			}

			// Compare as data, so field order and formatting cannot fail it.
			var want, have any
			if err := json.Unmarshal(raw, &want); err != nil {
				t.Fatalf("golden: %v", err)
			}
			gotJSON, err := json.Marshal(got)
			if err != nil {
				t.Fatalf("marshal: %v", err)
			}
			if err := json.Unmarshal(gotJSON, &have); err != nil {
				t.Fatalf("unmarshal: %v", err)
			}

			if !equalJSON(normalise(want), normalise(have)) {
				t.Errorf("subtree does not match the frozen golden\n got: %s\nwant: %s", gotJSON, raw)
			}
		})
	}
}

// Roots at the node the caller binds to, which is what makes the 404 rule
// coherent rather than a disclosure.
func TestSubtreeRootsAtTheBoundNode(t *testing.T) {
	a := authorizer(t)
	for _, p := range personas(t) {
		got := a.Subtree(p.PartyUUID)
		if got == nil {
			t.Errorf("%s: no subtree", p.ID)
			continue
		}
		if got.ID != p.NodeUUID {
			t.Errorf("%s: rooted at %s, the persona binds at %s", p.ID, got.ID, p.NodeUUID)
		}
		if string(got.NodeType) != p.NodeType {
			t.Errorf("%s: root is %s, want %s", p.ID, got.NodeType, p.NodeType)
		}
	}
}

func equalJSON(a, b any) bool {
	x, _ := json.Marshal(a)
	y, _ := json.Marshal(b)
	return string(x) == string(y)
}

// normalise sorts siblings before comparing, because the CONTRACT DOES NOT
// SPECIFY THEIR ORDER.
//
// `Node.children` is a plain array in api/openapi.yaml, and the spec orders
// things explicitly where it means to — heatmap columns are "ordered by
// blockers descending". The persona goldens happen to carry the order of the
// `Boundaries` table inside internal/fixtures, which is a property of the
// generator and not of any document: nothing in the OSCAL determines whether
// Public Portal precedes Identity Services.
//
// Asserting that order here would make internal/tree responsible for
// reproducing a generator artifact, and would quietly contradict the rule that
// every node must be recomputable from exported OSCAL alone. So the comparison
// is order-insensitive among siblings and exact in everything else. The system
// tier is a different case and is NOT normalised away: those children come from
// one document, so their order is the SSP's own and is reproducible.
func normalise(v any) any {
	m, ok := v.(map[string]any)
	if !ok {
		return v
	}
	kids, ok := m["children"].([]any)
	if !ok {
		return m
	}
	for i := range kids {
		kids[i] = normalise(kids[i])
	}
	sort.Slice(kids, func(i, j int) bool { return sortKey(kids[i]) < sortKey(kids[j]) })
	m["children"] = kids
	return m
}

func sortKey(v any) string {
	m, ok := v.(map[string]any)
	if !ok {
		return ""
	}
	s, _ := m["id"].(string)
	return s
}
